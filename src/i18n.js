export function makeT(lang) {
  const table = STRINGS[lang] || STRINGS.es;
  return (key, vars) => {
    let s = table[key] ?? STRINGS.es[key] ?? key;
    if (vars) for (const k in vars) s = s.replaceAll(`{${k}}`, vars[k]);
    return s;
  };
}
